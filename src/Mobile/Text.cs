public static class Text
{
    public static string EmptyIfNull(string? s) => s is null ? "" : s;

    /// <summary>???? JSON ??? ?? ?????? ??? ?????? ??????? ??? ?? ??? ????? ?????.</summary>
    public static string Json(string s)
    {
        if (string.IsNullOrEmpty(s)) return "";
        var sb = new StringBuilder();
        foreach (var c in s)
        {
            if (c == '\\') sb.Append("\\\\");
            else if (c == '"') sb.Append("\\\"");
            else if (c == '\n') sb.Append("\\n");
            else if (c == '\r') sb.Append("\\r");
            else if (c == '\t') sb.Append("\\t");
            else sb.Append(c);
        }
        return sb.ToString();
    }

    public static byte[] Utf8Encode(string s) => Encoding.UTF8.GetBytes(s);
    public static string Utf8Decode(byte[] b) => Encoding.UTF8.GetString(b);
    
    public static byte[] ReadBinaryFile(string path)
    {
        try { return File.ReadAllBytes(path); }
        catch { return new byte[0]; }
    }

    public static byte[] AsciiBytes(string s) => Encoding.ASCII.GetBytes(s);
}
