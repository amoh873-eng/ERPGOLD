namespace ERPSystem.Domain.Enums;

/// <summary>
/// دورة حياة سندات القبض والصرف الجديدة فقط (D1-A): مسودة ← اعتماد ← ترحيل ← إلغاء.
/// مُستقل تمامًا عن <see cref="DocumentStatus"/> المستخدم في المستندات القائمة،
/// فلا تتأثر دورة حياة أي مستند موجود (فواتير/مردودات/سندات مصروف/شيكات…).
/// </summary>
public enum VoucherStatus
{
    /// <summary>مسودة - Draft: قابلة للتعديل، ولا يُنشأ قيد محاسبي عند الحفظ.</summary>
    Draft = 1,

    /// <summary>معتمد - Approved: جاهز للترحيل، ولا يُنشأ قيد بعد.</summary>
    Approved = 2,

    /// <summary>مرحّل - Posted: أُنشئ قيده المحاسبي وثُبّت رقمه.</summary>
    Posted = 3,

    /// <summary>ملغى - Cancelled: أُلغي قبل الترحيل مع الحفاظ على الأثر التاريخي.</summary>
    Cancelled = 4,

    /// <summary>
    /// معكوس - Reversed (PU-04): سند مُرحَّل أُنشئ له مستند عكس مُرحَّل بالكامل.
    /// السند الأصلي يبقى محفوظًا (لا حذف ولا تعديل)؛ الحالة تعني «لا أثر صافٍ بعد العكس».
    /// </summary>
    Reversed = 5
}
