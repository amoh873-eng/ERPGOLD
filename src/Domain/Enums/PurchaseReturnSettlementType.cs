namespace ERPSystem.Domain.Enums;

/// <summary>
/// PU-04 (N-3) — نوع تسوية مردود المشتريات.
///
/// التمييز إلزامي لأن الأثر المحاسبي يختلف:
///  • OnAccountCredit: يخفض مديونية المورد (مدين 2200) ويُخفض رصيد المورد التشغيلي.
///  • CashRefund: رد نقدي فعلي (مدين 1100) **ولا يخفض** رصيد المورد التشغيلي.
///
/// لا يوجد نوع «مطالبة» لأن حساب المطالبات لم يُعتمد بعد (N-4) — أي محاولة
/// لاستخدام مطالبة تُرفض برسالة صريحة بدل اختراع حساب.
/// </summary>
public enum PurchaseReturnSettlementType
{
    /// <summary>مردود يخفض الذمم (على الحساب) — الافتراضي للفواتير الآجلة.</summary>
    OnAccountCredit = 1,

    /// <summary>مردود سُدِّد نقدًا فعليًا (يتطلب مرجع إثبات).</summary>
    CashRefund = 2
}
